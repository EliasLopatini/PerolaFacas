const galleryTimers = {};


/**
 * Inicia rotação automática
 */
function initGallery(id) {


    const gallery =
        document.getElementById(
            "gal-" + id
        );


    if (!gallery) return;


    const total =
        parseInt(
            gallery.dataset.total,
            10
        );


    if (total < 2) return;



    if (galleryTimers[id]) {

        clearInterval(
            galleryTimers[id]
        );

    }



    galleryTimers[id] =
        setInterval(
            () => {

                const current =
                    parseInt(
                        gallery.dataset.index,
                        10
                    );


                galGo(
                    id,
                    (current + 1) % total
                );


            },
            3500
        );



    gallery.addEventListener(
        "mouseenter",
        () =>
            clearInterval(
                galleryTimers[id]
            )
    );



    gallery.addEventListener(
        "mouseleave",
        () =>
            initGallery(id)
    );

}



/**
 * Troca imagem da galeria
 */
function galGo(id, index) {


    const gallery =
        document.getElementById(
            "gal-" + id
        );


    if (!gallery) return;



    gallery.dataset.index =
        index;



    gallery
        .querySelectorAll("img")
        .forEach(
            img =>
                img.classList.toggle(
                    "active",
                    Number(img.dataset.i) === index
                )
        );

}



