/**
 * Formata valores em reais
 */
function formatBRL(cents) {

    return new Intl.NumberFormat(
        "pt-BR",
        {
            style: "currency",
            currency: "BRL",
        }
    ).format(
        (cents || 0) / 100
    );

}


/**
 * Abre conversa no WhatsApp
 */
function waLink(text) {

    window.open(
        `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(text)}`,
        "_blank"
    );

    return false;

}


/**
 * Pede um produto específico no WhatsApp
 */
function orderProductWhatsapp(id) {

    const product =
        PRODUCTS.find(
            item =>
                item.id === id
        );


    if (!product) {
        return false;
    }


    const message =
        `Olá! Tenho interesse na ${product.name} ` +
        `(${formatBRL(product.price_cents)}).`;


    return waLink(message);

}


/**
 * Sistema de notificações
 */
function toast(message, type = "success") {

    const box = document.getElementById("toasts");

    const element = document.createElement("div");


    element.className =
        "toast " + type;


    element.textContent = message;


    box.appendChild(element);


    setTimeout(
        () => {

            element.remove();

        },
        2600
    );

}


/**
 * Proteção contra HTML inserido pelo usuário
 */
function escapeHtml(value) {

    return String(value ?? "")
        .replace(
            /[&<>"']/g,
            character =>
                ({
                    "&": "&amp;",
                    "<": "&lt;",
                    ">": "&gt;",
                    '"': "&quot;",
                    "'": "&#39;",
                }[character])
        );

}


function escapeAttr(value) {

    return escapeHtml(value);

}


/**
 * Retorna somente imagens válidas
 */
function productPhotos(product) {

    return (
        product.images || []
    )
    .filter(Boolean);

}


/* ==========================================================
   Carrinho - armazenamento local
   ========================================================== */


/**
 * Carrega carrinho salvo no navegador
 */
function loadCart() {

    try {

        const saved =
            localStorage.getItem(LS_CART);


        state.cart =
            saved
                ? JSON.parse(saved)
                : [];


    } catch (error) {

        state.cart = [];

    }

}


/**
 * Salva carrinho no navegador
 */
function saveCart() {

    try {

        localStorage.setItem(
            LS_CART,
            JSON.stringify(state.cart)
        );


    } catch (error) {

        console.warn(
            "Não foi possível salvar o carrinho."
        );

    }

}

/**
 * Soma total do carrinho
 */
function cartTotalCents() {

    return state.cart.reduce(
        (total, item) => {

            const product =
                PRODUCTS.find(
                    product =>
                        product.id === item.id
                );


            if (!product) {
                return total;
            }


            return (
                total +
                product.price_cents *
                item.qty
            );

        },
        0
    );

}


/**
 * Quantidade total de produtos
 */
function cartCount() {

    return state.cart.reduce(
        (sum, item) =>
            sum + item.qty,
        0
    );

}
