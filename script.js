let lb = {

    open:false,

    photos:[],

    index:0,

    name:"",

};



function openLightbox(productId,index) {


    const product =
        PRODUCTS.find(
            item =>
                item.id === productId
        );


    const photos =
        productPhotos(product);



    if (!photos.length) return;



    lb.photos =
        photos;


    lb.index =
        index;


    lb.name =
        product.name;


    lb.open =
        true;



    renderLightbox();



    document
        .getElementById(
            "lightboxOverlay"
        )
        .classList
        .add("show");



    document.body.style.overflow =
        "hidden";

}



function closeLightbox() {


    if (!lb.open) return;



    lb.open =
        false;



    document
        .getElementById(
            "lightboxOverlay"
        )
        .classList
        .remove("show");



    document.body.style.overflow =
        "";

}



function lbNav(direction) {


    const total =
        lb.photos.length;



    lb.index =
        (
            lb.index +
            direction +
            total
        )
        %
        total;



    renderLightbox();

}



function renderLightbox() {


    const image =
        document.getElementById(
            "lightboxImg"
        );


    image.src =
        lb.photos[lb.index];


    image.alt =
        lb.name;



    const counter =
        document.getElementById(
            "lightboxCounter"
        );


    counter.textContent =
        `${lb.index + 1} / ${lb.photos.length}`;


}



